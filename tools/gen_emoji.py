#!/usr/bin/env python3
"""Builds the color emoji the panel draws inside messages.

Reads tools/emoji_list.txt, downloads each emoji from Twemoji (CC BY 4.0,
https://github.com/jdecked/twemoji), scales it to the three message font sizes and writes:

  main/emoji/emoji.bin       pixels, LVGL RGB565A8 (RGB565 plane, then the alpha plane)
  main/emoji/emoji_index.c   image descriptors pointing into emoji.bin + a sorted lookup table

Needs Pillow. Downloads are cached in --cache (default: a folder next to this script's output
that git ignores).

    python3 tools/gen_emoji.py
"""
import argparse
import io
import os
import struct
import sys
import urllib.request

from PIL import Image

TWEMOJI = "https://cdn.jsdelivr.net/gh/jdecked/twemoji@15.1.0/assets/72x72/{}.png"
SIZES = [16, 22, 28]   # for font_pt_14, font_pt_20, font_pt_28 (line heights 18, 25, 35)
BIG = 36               # weather icon on the dashboard: sun, moon, cloud
BIG_CPS = [0x2600, 0x1F319, 0x2601]

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def codepoints(path):
    out = []
    for line in open(path, encoding="utf-8"):
        if line.startswith("#"):
            continue
        for ch in line:
            cp = ord(ch)
            if ch.isspace() or cp == 0xFE0F:
                continue
            if cp not in out:
                out.append(cp)
    return sorted(out)


def fetch(cp, cache):
    name = f"{cp:x}.png"
    path = os.path.join(cache, name)
    if not os.path.exists(path):
        with urllib.request.urlopen(TWEMOJI.format(f"{cp:x}"), timeout=20) as r:
            data = r.read()
        with open(path, "wb") as f:
            f.write(data)
    with open(path, "rb") as f:
        return Image.open(io.BytesIO(f.read())).convert("RGBA")


def rgb565a8(img):
    rgb = bytearray()
    alpha = bytearray()
    px = img.tobytes()
    for i in range(0, len(px), 4):
        r, g, b, a = px[i:i + 4]
        v = ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)
        rgb += struct.pack("<H", v)
        alpha.append(a)
    return bytes(rgb + alpha)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--cache", default=os.path.join(ROOT, "build", "twemoji_cache"))
    a = ap.parse_args()
    os.makedirs(a.cache, exist_ok=True)

    cps = codepoints(os.path.join(ROOT, "tools", "emoji_list.txt"))
    blob = bytearray()
    rows = []
    for cp in cps:
        try:
            src = fetch(cp, a.cache)
        except Exception as e:
            sys.exit(f"U+{cp:04X}: {e}")
        offs = []
        for s in SIZES:
            data = rgb565a8(src.resize((s, s), Image.LANCZOS))
            offs.append(len(blob))
            blob += data
        rows.append((cp, offs))

    big = []
    for cp in BIG_CPS:
        big.append(len(blob))
        blob += rgb565a8(fetch(cp, a.cache).resize((BIG, BIG), Image.LANCZOS))

    out_dir = os.path.join(ROOT, "main", "emoji")
    os.makedirs(out_dir, exist_ok=True)
    with open(os.path.join(out_dir, "emoji.bin"), "wb") as f:
        f.write(blob)

    lines = [
        "// Generated by tools/gen_emoji.py from tools/emoji_list.txt. Don't edit.",
        "// Twemoji graphics (c) Twitter, Inc. and other contributors, CC BY 4.0.",
        '#include "emoji.h"',
        "",
        'extern const uint8_t EMOJI_BIN[] asm("_binary_emoji_bin_start");',
        "",
        "#define IMG(off, s) {.header = {.magic = LV_IMAGE_HEADER_MAGIC, .cf = LV_COLOR_FORMAT_RGB565A8, "
        ".w = s, .h = s, .stride = (s) * 2}, .data_size = (s) * (s) * 3, .data = EMOJI_BIN + (off)}",
        "",
        f"const uint8_t EMOJI_SIZES[EMOJI_N_SIZES] = {{{', '.join(map(str, SIZES))}}};",
        "",
        "const emoji_t EMOJI[] = {",
    ]
    for cp, offs in rows:
        imgs = ", ".join(f"IMG({o}, {s})" for o, s in zip(offs, SIZES))
        lines.append(f"    {{0x{cp:X}, {{{imgs}}}}},   // {chr(cp)}")
    lines += ["};", "", "const int EMOJI_COUNT = sizeof(EMOJI) / sizeof(EMOJI[0]);", "",
              "// weather icon: sun, moon, cloud",
              "const lv_image_dsc_t EMOJI_BIG[EMOJI_N_BIG] = {"]
    lines += [f"    IMG({o}, {BIG}),   // {chr(cp)}" for o, cp in zip(big, BIG_CPS)]
    lines += ["};", ""]
    with open(os.path.join(out_dir, "emoji_index.c"), "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    print(f"{len(rows)} emoji, {len(blob) / 1024:.0f} KB")


if __name__ == "__main__":
    main()
